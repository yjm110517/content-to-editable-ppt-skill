        _cli("run-roundtrip", "--state", str(gate / "state.json"), "--candidate-pptx", str(p4 / "reconstruction-candidate.pptx"), "--p4-manifest", str(p4 / "reconstruction-manifest.json"), "--output", str(gate / "roundtrip-report.json"), "--width-px", "1600", "--height-px", "900")
        # exception review: no exception pages expected for D03
        qa = json.loads((gate / "qa-report.json").read_text(encoding="utf-8"))
        evidence_out = _cli("prepare-exception-review", "--state", str(gate / "state.json"), "--qa-report", str(gate / "qa-report.json"), "--output", str(gate / "exception-evidence.json"))
