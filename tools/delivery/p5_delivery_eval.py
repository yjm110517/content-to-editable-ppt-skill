"""P5 deterministic gate tool.

--deterministic            Run the D03 deterministic chain (authority / final integrity with real
                           PowerPoint / deck QA / roundtrip / package candidate) plus D05/D08
                           fixtures. Ends in live_review_pending. formal_delivery_created = false.
                           The Gate report is generated by this tool, never handwritten.

--consume-live-review P    Validate a real Deck Consistency Review evidence package (call_manifest,
                           call_record, contact sheets, raw/finalized responses, hash bindings),
                           then re-run policy, decision, formal packaging, and the final gate.

Consumption requires a live review (ADR-040); frozen replays are rejected.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SCRIPTS = ROOT / "content-to-editable-ppt" / "scripts"
MANAGE = SCRIPTS / "manage_delivery.py"
if str(SCRIPTS) not in sys.path:
    sys.path.insert(0, str(SCRIPTS))


def _cli(*args: str) -> dict:
    completed = subprocess.run([sys.executable, str(MANAGE), *args], capture_output=True, text=True, encoding="utf-8", errors="replace")
    payload = json.loads(completed.stdout) if completed.stdout.strip() else {"status": "error", "error": {"issues": [{"code": "cli_failure", "message": completed.stderr[:400]}]}}
    if completed.returncode or payload.get("status") != "ok":
        raise RuntimeError(json.dumps(payload.get("error"), ensure_ascii=False))
    return payload["outputs"]


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _make_deck(path: Path, kind: str, slide_count: int) -> None:
    from pptx import Presentation
    from pptx.util import Emu
    presentation = Presentation()
    if kind == "D05":
        from pptx.chart.data import CategoryChartData
        from pptx.enum.chart import XL_CHART_TYPE
        for index in range(slide_count):
            slide = presentation.slides.add_slide(presentation.slide_layouts[6])
            box = slide.shapes.add_textbox(Emu(100000), Emu(100000), Emu(3000000), Emu(200000))
            box.text_frame.text = f"D05 chart card slide {index + 1}"
            chart_data = CategoryChartData()
            chart_data.categories = ["A", "B"]
            chart_data.add_series("Series", (1, 2))
            slide.shapes.add_chart(XL_CHART_TYPE.COLUMN_CLUSTERED, Emu(400000), Emu(400000), Emu(3000000), Emu(2000000), chart_data)
    else:
        from pptx.enum.shapes import MSO_CONNECTOR
        for index in range(slide_count):
            slide = presentation.slides.add_slide(presentation.slide_layouts[6])
            box = slide.shapes.add_textbox(Emu(100000), Emu(100000), Emu(3000000), Emu(200000))
            box.text_frame.text = f"D08 order-sensitive connector slide {index + 1}"
            slide.shapes.add_connector(MSO_CONNECTOR.STRAIGHT, Emu(100000), Emu(500000), Emu(3000000), Emu(500000))
    presentation.save(str(path))


